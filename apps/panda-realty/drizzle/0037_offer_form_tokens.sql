CREATE TABLE IF NOT EXISTS panda_realty.offer_form_tokens (
  offer_form_token_id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  property_entity_id  bigint NOT NULL REFERENCES panda_realty.property_entities(property_entity_id) ON DELETE CASCADE,
  property_list_id    bigint NOT NULL REFERENCES panda_realty.panda_properties(property_list_id) ON DELETE CASCADE,
  token               text NOT NULL UNIQUE,
  created_at          timestamp DEFAULT now()
);
