CREATE TABLE IF NOT EXISTS panda_realty.offer_form_submissions (
  offer_form_submission_id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  offer_form_token_id      bigint NOT NULL REFERENCES panda_realty.offer_form_tokens(offer_form_token_id) ON DELETE CASCADE,
  property_entity_id       bigint NOT NULL REFERENCES panda_realty.property_entities(property_entity_id) ON DELETE CASCADE,
  property_list_id         bigint NOT NULL REFERENCES panda_realty.panda_properties(property_list_id) ON DELETE CASCADE,
  -- Buyer details
  buyer1_name              citext,
  buyer2_name              citext,
  buyer_address            text,
  buyer_phone              citext,
  buyer_email              citext,
  -- Offer
  offer_amount             citext,
  is_cash_buyer            boolean,
  settlement_period        citext,
  -- Subject to sale
  is_subject_to_sale       boolean,
  sale_timeframe_days      citext,
  sale_property_status     citext,
  sale_settlement_date     citext,
  -- Subject to finance
  is_subject_to_finance    boolean,
  finance_pre_approved     boolean,
  finance_days_to_approve  citext,
  finance_bank             citext,
  finance_bank_phone       citext,
  -- Solicitor
  solicitor_name           citext,
  solicitor_phone          citext,
  solicitor_address        text,
  solicitor_email          citext,
  -- Timestamps
  submitted_at             timestamp DEFAULT now(),
  created_at               timestamp DEFAULT now()
);
