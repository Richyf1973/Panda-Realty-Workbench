-- Create panda_realty.agents table
CREATE TABLE IF NOT EXISTS panda_realty.agents (
  agent_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_name citext NOT NULL,
  email citext,
  phone citext,
  created_at timestamp DEFAULT now(),
  updated_at timestamp
);

-- Add agent_id FK column to property_list_notes
ALTER TABLE panda_realty.property_list_notes
  ADD COLUMN IF NOT EXISTS agent_id bigint REFERENCES panda_realty.agents(agent_id) ON DELETE SET NULL;
