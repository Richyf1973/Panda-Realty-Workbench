"""Generate SQL that upgrades the June-schema database to the live (Oct 2026) design.

Input: live/schema2.csv (kind,name,detail) exported from Supabase.
Output (stdout): idempotent-ish SQL delta.
"""
import csv
import json
import re
import subprocess
import sys

LIVE = "/home/claude/live"
BASE_DB = sys.argv[1] if len(sys.argv) > 1 else "panda"

tables = json.load(open(f"{LIVE}/tables.json"))
rows = list(csv.DictReader(open(f"{LIVE}/schema2.csv")))
funcs = {r["name"]: r["detail"] for r in rows if r["kind"] == "function"}


def psql(q):
    r = subprocess.run(["psql", "-h", "localhost", "-U", "postgres", "-d", BASE_DB, "-Atc", q],
                       capture_output=True, text=True, check=True)
    return r.stdout.split()


base_tables = set(psql("select table_name from information_schema.tables where table_schema='panda_realty'"))


def base_cols(tb):
    return set(psql(f"select column_name from information_schema.columns "
                    f"where table_schema='panda_realty' and table_name='{tb}'"))


def coltype(spec):
    spec = spec.replace("USER-DEFINED", "citext")
    if spec.startswith("ARRAY"):
        spec = ("bytea[]" if "bytea" in spec else "text[]") + spec[5:]
    return spec


def split_detail(d):
    cols, rest = d.split("\n-- constraints\n", 1)
    cons, rest = rest.split("\n-- indexes\n", 1)
    idx, rest = rest.split("\n-- triggers\n", 1)
    trg = rest.split("\n-- rows:")[0]
    lines = lambda s: [l for l in s.split("\n") if l.strip()]
    return lines(cols), lines(cons), lines(idx), lines(trg)


out = ["set search_path = panda_realty, public;", "create extension if not exists citext;", "create extension if not exists moddatetime;"]
create, addcols, constraints, indexes, triggers = [], [], [], [], []

for tb, d in sorted(tables.items()):
    cols, cons, idx, trg = split_detail(d)
    con_names = set()
    pk_def = None
    for l in cons:
        nm, df = l.split(": ", 1)
        con_names.add(nm)
        if "PRIMARY KEY" in df:
            pk_def = df
        else:
            constraints.append((tb, nm, df))
    pk_single = re.fullmatch(r"PRIMARY KEY \((\w+)\)", pk_def or "")
    if tb not in base_tables:
        defs = []
        for c in cols:
            n, spec = c.split(" ", 1)
            spec = coltype(spec)
            if pk_single and n == pk_single.group(1) and "default" not in spec \
                    and spec.split()[0] in ("bigint", "integer"):
                spec = spec.split()[0] + " generated by default as identity not null"
            defs.append(f'  "{n}" {spec}')
        if pk_def:
            defs.append(f"  {pk_def}")
        create.append(f'create table panda_realty."{tb}" (\n' + ",\n".join(defs) + "\n);")
    else:
        have = base_cols(tb)
        for c in cols:
            n, spec = c.split(" ", 1)
            if n not in have:
                addcols.append(f'alter table panda_realty."{tb}" add column "{n}" {coltype(spec)};')
    for l in idx:
        m = re.match(r"CREATE (?:UNIQUE )?INDEX (\w+) ON", l)
        if m and m.group(1) in con_names:
            continue  # created by the constraint
        indexes.append(l)
    triggers += trg

seqs = sorted(set(re.findall(r"nextval\('([\w.]+)'", "\n".join(create + addcols))))
out += [f"create sequence if not exists {q};" for q in seqs]
out.append("-- functions")
for n, body in funcs.items():
    if n != "public.slugify":
        out.append(body.rstrip() + ";")
out += create + addcols
out.append("-- functions again (those that reference tables)")
for n, body in funcs.items():
    if n != "public.slugify":
        out.append(body.rstrip() + ";")
out.append("-- constraints")
for tb, nm, df in sorted(constraints, key=lambda x: "FOREIGN KEY" in x[2]):
    out.append(
        f'do $$ begin alter table panda_realty."{tb}" add constraint "{nm}" {df}; '
        f"exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $$;")
out.append("-- indexes")
for l in indexes:
    l = l.replace("CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ").replace(
        "CREATE UNIQUE INDEX ", "CREATE UNIQUE INDEX IF NOT EXISTS ")
    out.append(l + ";")
out.append("-- triggers")
for l in triggers:
    m = re.match(r"CREATE (?:CONSTRAINT )?TRIGGER (\w+) .*? ON (\S+)", l)
    out.append(f"drop trigger if exists {m.group(1)} on {m.group(2)};\n{l};")
print("\n".join(out))
