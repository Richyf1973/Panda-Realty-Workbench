// Regenerates lib/sale-timeline/timeline-html.ts from lib/sale-timeline/timeline.html.
// Run after editing the timeline page:  node tools/build-sale-timeline.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../lib/sale-timeline")
const html = fs.readFileSync(path.join(dir, "timeline.html"), "utf8")
const out = `// GENERATED by tools/build-sale-timeline.mjs from timeline.html. Do not edit by hand.\nexport const TIMELINE_HTML: string = ${JSON.stringify(html)}\n`
fs.writeFileSync(path.join(dir, "timeline-html.ts"), out)
console.log(`timeline-html.ts written (${html.length} chars)`)
